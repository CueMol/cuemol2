/**
 * @file mac/swapScript.ts
 * @description The shell script that swaps the staged app in after the app quits.
 *
 * Runs detached from the app, from a copy outside the bundle (the bundle is
 * what it moves). Steps:
 *   1. wait for the app process to exit;
 *   2. move the installed app to the backup slot and the staged one into
 *      its place (rename on the same volume), putting the old one back if
 *      the second move fails;
 *   3. launch the new app and wait for it to write the launch marker, which
 *      it does once its main window is up (by the renderer's signal);
 *   4. marker seen: delete the backup. No marker in time, or the new app's
 *      process is gone: kill it, restore the backup and launch that.
 * The outcome goes to a JSON file the app reads on its next start.
 *
 * Squirrel.Mac and Sparkle restore the old app only when the swap itself
 * fails; step 3 is added because an unsigned app with bundled native
 * libraries is most likely to break at launch.
 */

/** Paths and limits for {@link buildSwapScript}. */
export interface SwapScriptParams {
  /** PID to wait for. */
  parentPid: number
  /** The installed `.app`. */
  appPath: string
  /** The staged new `.app`. */
  stagingPath: string
  /** Where the old `.app` waits until the new one has started. */
  backupPath: string
  /** Where a failed new `.app` is moved before it is deleted. */
  failedPath: string
  /** File the new app writes once it is up. */
  markerPath: string
  /** File the outcome goes to. */
  resultPath: string
  /** Hand-off file to delete when done. */
  pendingPath: string
  logPath: string
  from: string
  to: string
  /** Seconds to wait for the app to exit. */
  exitTimeout: number
  /** Seconds to wait for the marker. */
  launchTimeout: number
  /** Seconds after launch before a missing process counts as a failed start. */
  processGrace: number
}

/** Single-quote `s` for /bin/sh. */
function q(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`
}

/** The script text; run it with `/bin/sh <file>`. */
export function buildSwapScript(p: SwapScriptParams): string {
  return `#!/bin/sh
# Generated by @cuemol/updater (mac/swapScript.ts). Swaps a staged CueMol3.app in.
APP=${q(p.appPath)}
STAGING=${q(p.stagingPath)}
BACKUP=${q(p.backupPath)}
FAILED=${q(p.failedPath)}
MARKER=${q(p.markerPath)}
RESULT=${q(p.resultPath)}
PENDING=${q(p.pendingPath)}
LOG=${q(p.logPath)}
PARENT=${p.parentPid}
FROM=${q(p.from)}
TO=${q(p.to)}

log() { echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*" >> "$LOG"; }
result() {
  printf '{"outcome":"%s","from":"%s","to":"%s","detail":"%s"}\\n' "$1" "$FROM" "$TO" "$2" > "$RESULT"
  rm -f "$PENDING" "$MARKER"
  log "result: $1 $2"
}
running() { pgrep -f "$APP/Contents/MacOS/" > /dev/null 2>&1; }

log "swap $FROM -> $TO, waiting for pid $PARENT"
# Limits are measured on the clock: counting loop turns ran long, since each
# turn also spends time in pgrep.
start=$(date +%s)
elapsed() { echo $(( $(date +%s) - start )); }
while kill -0 "$PARENT" 2> /dev/null; do
  if [ "$(elapsed)" -ge ${p.exitTimeout} ]; then result aborted "the app did not exit"; exit 1; fi
  sleep 0.2
done

rm -f "$MARKER"
rm -rf "$BACKUP" "$FAILED"
mkdir -p "$(dirname "$BACKUP")"
if ! mv "$APP" "$BACKUP" >> "$LOG" 2>&1; then
  result failed "could not move the installed app aside"; exit 1
fi
if ! mv "$STAGING" "$APP" >> "$LOG" 2>&1; then
  mv "$BACKUP" "$APP" >> "$LOG" 2>&1
  result failed "could not move the new app into place"; exit 1
fi
log "swapped, launching the new app"
env -u ELECTRON_RUN_AS_NODE open "$APP" >> "$LOG" 2>&1

start=$(date +%s)
while [ ! -f "$MARKER" ]; do
  t=$(elapsed)
  dead=0
  if [ "$t" -ge ${p.processGrace} ] && ! running; then dead=1; fi
  if [ $dead = 1 ] || [ "$t" -ge ${p.launchTimeout} ]; then
    log "the new app did not start (exited=$dead), rolling back"
    pkill -f "$APP/Contents/" >> "$LOG" 2>&1
    sleep 1
    # The failed app must be gone from APP before the backup goes back:
    # mv onto an existing directory would nest the backup inside it.
    mkdir -p "$(dirname "$FAILED")"
    mv "$APP" "$FAILED" >> "$LOG" 2>&1 || rm -rf "$APP"
    if ! mv "$BACKUP" "$APP" >> "$LOG" 2>&1; then
      result failed "could not restore the previous version from $BACKUP"; exit 1
    fi
    rm -rf "$FAILED"
    result rolledBack "the new version did not start"
    env -u ELECTRON_RUN_AS_NODE open "$APP" >> "$LOG" 2>&1
    exit 1
  fi
  sleep 0.2
done

rm -rf "$BACKUP"
result ok ""
exit 0
`
}
